"""Two-policy generate function for multi-policy training (solver + verifier).

For each prompt, emits one group per policy, stamped with
``Sample.trainer_model_id`` so the shared fully-async queue can shard samples
per policy. Each policy's samples are generated against that policy's own
router (``args.vllm_model_routers[model_id]``), so solver samples are always
generated by solver weights and verifier samples by verifier weights.

Wire with ``--custom-generate-function-path examples.multi_policy.generate_solver_verifier.generate``.
"""

import copy

from vime.utils.http_utils import post
from vime.utils.types import Sample

POLICIES = ("solver", "verifier")

_VERIFIER_TEMPLATE = (
    "Problem: {prompt}\n\nCandidate solution:\n{response}\n\n"
    "Judge whether the candidate solution is correct. Explain briefly, then give the final verdict."
)


def _router_url(args, model_id: str) -> str:
    routers = getattr(args, "vllm_model_routers", None) or {}
    if model_id not in routers:
        raise ValueError(
            f"multi-policy generate: no router for policy {model_id!r}; declare one vLLM model per policy "
            f"(update_weights: true) in --vllm-config, known: {sorted(routers)}"
        )
    ip, port = routers[model_id]
    return f"http://{ip}:{port}/inference/v1/generate"


async def _generate_on_policy(args, sample: Sample, model_id: str, prompt_text: str, sampling_params: dict) -> Sample:
    payload = {
        "text": prompt_text,
        "sampling_params": {
            "temperature": sampling_params.get("temperature", 0.8),
            "top_p": sampling_params.get("top_p", 1.0),
            "max_new_tokens": sampling_params.get("max_new_tokens", 256),
        },
        "return_logprob": True,
    }
    result = await post(_router_url(args, model_id), payload)

    out = copy.deepcopy(sample)
    out.prompt = prompt_text
    out.trainer_model_id = model_id
    out.rollout_id = sample.index if sample.rollout_id is None else sample.rollout_id
    meta = result.get("meta_info", {})
    out.response = result.get("text", "")
    out.response_length = meta.get("completion_tokens", 0)
    if meta.get("output_token_logprobs"):
        out.rollout_log_probs = [lp for _, lp, *_ in meta["output_token_logprobs"]]
    out.status = Sample.Status.COMPLETED if out.response_length else Sample.Status.ABORTED
    out.reward = None  # computed by the RM stage downstream
    return out


async def generate(args, sample: Sample, sampling_params: dict, evaluation: bool = False) -> list[Sample]:
    solver = await _generate_on_policy(args, sample, "solver", sample.prompt, sampling_params)
    verifier_prompt = _VERIFIER_TEMPLATE.format(prompt=sample.prompt, response=solver.response)
    verifier = await _generate_on_policy(args, sample, "verifier", verifier_prompt, sampling_params)
    return [solver, verifier]
